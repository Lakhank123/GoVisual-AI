from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field

class CreativeRequest(BaseModel):
    """
    Structured internal request object for GoVisual 2.0 representing a creative generation request.
    This creates a clean contract between the creative planning layer and the image generation layer.
    """
    marketing_requirement: Optional[str] = None
    product_info: Optional[Dict[str, Any]] = Field(default_factory=dict)
    reference_images: List[bytes] = Field(default_factory=list)
    logo_image: Optional[bytes] = None
    logo_position: str = "top-right"
    brand_dna: Optional[Dict[str, Any]] = Field(default_factory=dict)
    creative_style: Optional[str] = None
    composition_requirements: Optional[str] = None
    aspect_ratio: str = "1:1"
    resolution: str = "1024x1024"
    candidate_count: int = 1
    generation_options: Dict[str, Any] = Field(default_factory=dict)
    # The prompt actually generated by the creative planner/prompt engine for the underlying model
    computed_prompt: Optional[str] = None
    candidate_id: str = Field(default="")
    strategy_name: str = Field(default="")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class CreativeResult(BaseModel):
    """
    Structured internal result object conceptually containing the output from an ImageGenerationProvider.
    """
    candidate_id: str = Field(default="")
    strategy_name: str = Field(default="")
    image_url: str = Field(default="")
    image_bytes: Optional[bytes] = None
    provider: str
    model: str
    prompt_used: Optional[str] = None
    references_used: List[str] = Field(default_factory=list)
    generation_parameters: Dict[str, Any] = Field(default_factory=dict)
    latency_seconds: float = 0.0
    latency: float = 0.0
    status: str = "SUCCESS"  # "SUCCESS" or "FAILED"
    error: Optional[str] = None
    reference_conditioned: bool = False
    metadata: Dict[str, Any] = Field(default_factory=dict)
